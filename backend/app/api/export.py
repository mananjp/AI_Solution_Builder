class DeployRequest(BaseModel):
    repo_name: str
    description: str = ""
    private: bool = False


@router.post("/{solution_id}/deploy")
async def deploy_solution(
    solution_id: UUID,
    payload: DeployRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> dict[str, Any]:
    """One-Click Deploy: push the generated manifest to a new GitHub repository."""
    solution, bundle = await _load_bundle(solution_id, current_user, db)

    if not payload.repo_name or not re.fullmatch(r"[A-Za-z0-9_-]+", payload.repo_name):
        raise HTTPException(
            status_code=400,
            detail="repo_name must be a single slug (letters, digits, dashes, underscores)",
        )

    await require_and_deduct_credit(
        db, current_user, "export", f"One-click deploy: {solution.title}", solution_id=solution_id
    )

    # Same token source as the MVP deployer: per-user PAT first, server global
    # fallback — a user can't guess between two unrelated token paths.
    raw_user_token = str((current_user.settings or {}).get("github_token", ""))
    gh_token = decrypt_secret(raw_user_token) if raw_user_token else settings.GITHUB_TOKEN

    files = build_repo_files(bundle, _github_workflow())
    try:
        result = await deploy_to_github(
            gh_token,
            payload.repo_name,
            files,
            description=payload.description,
            private=payload.private,
        )
    except DeployError as err:
        raise HTTPException(status_code=502, detail=f"Deployment failed: {err}") from err

    return {"status": "deployed", **result, "message": "Repository created and manifest pushed."}
